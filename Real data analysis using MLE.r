n <- length(x)
# APTEILD PDF
APTEILD_pdf <- function(x, alpha, theta, beta, delta){
  x <- pmax(x, 1e-12)
  A <- log(alpha)/(alpha - 1)
  B <- delta * theta^2/(theta + beta)
  C <- (beta + x^delta)/x^(2*delta + 1)
  D <- exp(-theta/x^delta)
  expo <- (1 + (theta*beta)/(theta+beta)/x^delta) * D
  dens <- A * B * C * D * alpha^expo
  dens[dens <= 0 | !is.finite(dens)] <- 1e-16
  dens
}

#  CDF of APTEILD
APTEILD_cdf <- function(x, alpha, theta, beta, delta){
  x <- pmax(x, 1e-12)
  expo <- (1 + (theta*beta)/(theta+beta)/x^delta) * exp(-theta/x^delta)
  F <- (exp(log(alpha) * expo) - 1)/(alpha - 1)
  pmin(pmax(F, 0), 1)
}


# Negative log-likelihood
nll_APTEILD <- function(par){
  alpha <- par[1]
  theta <- exp(par[2])
  beta  <- par[3]
  delta <- par[4]
  -sum(log(APTEILD_pdf(x, alpha, theta, beta, delta)))
}
# MLE via GenSA
res <- GenSA(
  lower = c(0.01, -5, 0.01, 0.01),
  upper = c(5, 5, 10, 5),
  fn = nll_APTEILD
)

logLik <- -res$value
k <- length(res$par)

AIC <- 2*k - 2*logLik
BIC <- log(n)*k - 2*logLik


# Standard errors

H <- hessian(nll_APTEILD, res$par)
cov_mat <- solve(H)
se <- sqrt(abs(diag(cov_mat)))

est <- c(
  alpha = res$par[1],
  theta = exp(res$par[2]),
  beta  = res$par[3],
  delta = res$par[4]
)

se_tr <- c(se[1], est["theta"]*se[2], se[3], se[4])


# KS test
ks <- ks.test(x, function(q)
  APTEILD_cdf(q, est["alpha"], est["theta"], est["beta"], est["delta"])
)

# Output
cat("\nAPTEILD MLE Results\n")
print(round(est,6))
cat("\nStandard Errors\n")
print(round(se_tr,6))
cat("\nAIC =",round(AIC,3)," BIC =",round(BIC,3),"\n")
cat("KS =",round(ks$statistic,4)," p-value =",round(ks$p.value,4),"\n")

